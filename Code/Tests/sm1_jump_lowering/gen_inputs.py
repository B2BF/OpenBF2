#!/usr/bin/env python3
"""[CHOSEN, not recovered] SM1/2 jump lowering check (vkd3d patch 0014).

Compiles every case of cases.txt with the patched vkd3d-compiler (d3dbc), runs
`nativefx temp-check` (no temp component read before it is written) on each result and writes
sm1_jump_lowering_inputs.h: HLSL source, profile, entry and our bytecode per case, the input of the
Windows fixture (sm1_jump_lowering_win.cpp, run by sm1_jump_lowering.cmd) that validates the
bytecode with the real d3dx9/d3d9 and compiles the same HLSL with D3DX for comparison.

  gen_inputs.py --deps DIR            write the header (DIR: a nativefx deps/build directory)
  gen_inputs.py --deps DIR --check    fail unless the header matches and every case is clean
  gen_inputs.py --result FILE         check sm1_jump_lowering_result.txt from the Windows run, and run
                                      our bytecode against D3DX's (d3dx_code lines) in the D3D9
                                      interpreter of tools/macos/nativefx/d3dbc_compare.py

Exit status is nonzero on any compile failure, uninitialized temp read, header mismatch or
validation failure; the summary line counts each.
"""
import argparse, re, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def cases():
    text = (HERE / "cases.txt").read_text()
    parts = re.split(r"^=== (.*)$", text, flags=re.M)
    out = []
    for i in range(1, len(parts), 2):
        name, profile, entry = parts[i].split()
        out.append((name, profile, entry, parts[i + 1].lstrip("\n")))
    return out


def c_string(s):
    return "\n".join('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"' for line in s.splitlines())


def header(results):
    lines = ["// Generated by gen_inputs.py from cases.txt with the patched vkd3d-compiler (0001-0015).",
             "// Synthetic shaders and our own compiler output only. Do not edit.", "#pragma once", ""]
    for name, profile, entry, src, code, slot in results:
        words = [int.from_bytes(code[i:i + 4], "little") for i in range(0, len(code), 4)]
        lines.append(f"static const char kSrc_{name}[] =")
        lines.append(c_string(src) + ";")
        lines.append(f"static const unsigned long kCode_{name}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
        lines.append("};")
    lines += ["", "struct Sm1Case { const char* name; const char* profile; const char* entry; const char* source;",
              "                 const unsigned long* code; unsigned words;",
              "                 int knownSlotLimit; /* [TEMP] over the slot limit until piece 17b (mul as dp4/dp3) */ };",
              "static const Sm1Case kSm1Cases[] = {"]
    for name, profile, entry, src, code, slot in results:
        lines.append(f'    {{"{name}", "{profile}", "{entry}", kSrc_{name}, kCode_{name}, {len(code) // 4}, {int(slot)}}},')
    lines += ["};", ""]
    return "\n".join(lines)


def check_result(path):
    text = Path(path).read_text().splitlines()
    names = {c[0] for c in cases()}
    seen, bad = set(), 0
    for line in text:
        if line.startswith("case "):
            f = line.split()
            seen.add(f[1])
            if "status=valid" not in f and "status=known-slot-limit-17b" not in f:
                bad += 1
                print("FAIL:", line[:600])
        elif line.startswith("control ") and " ok=1" not in line:
            bad += 1
            print("FAIL:", line)
    # Semantics: our bytecode (the header) against D3DX's for every case D3DX compiled.
    sys.path.insert(0, str(HERE.parents[2] / "tools/macos/nativefx"))
    import d3dbc_compare
    header_text = (HERE / "sm1_jump_lowering_inputs.h").read_text()
    ours = {}
    for m in re.finditer(r"kCode_(\w+)\[\] = \{([^}]*)\}", header_text):
        ours[m.group(1)] = b"".join(int(w, 16).to_bytes(4, "little") for w in re.findall(r"0x[0-9a-f]+", m.group(2)))
    semantic_bad = semantic_ok = 0
    for line in text:
        if not line.startswith("d3dx_code "):
            continue
        f = line.split()
        theirs = b"".join(int(w, 16).to_bytes(4, "little") for w in f[2:])
        try:
            diff = d3dbc_compare.compare_named(theirs, ours[f[1]])
        except d3dbc_compare.Unsupported as e:
            diff = "not interpretable: %s" % e
        if diff:
            semantic_bad += 1
            print(f"FAIL semantics {f[1]}: {diff}")
        else:
            semantic_ok += 1
    print(f"semantics against D3DX: {semantic_ok} agree, {semantic_bad} differ")
    bad += semantic_bad
    summary = [l for l in text if l.startswith("summary ")]
    missing = names - seen
    print(f"result: {len(seen)} of {len(names)} cases reported, {bad} failed, {len(missing)} missing"
          + (f" ({', '.join(sorted(missing))})" if missing else ""))
    if summary:
        print(summary[-1])
    return 1 if bad or missing or not summary else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--deps", help="nativefx deps/build directory (vkd3d/vkd3d-compiler, tool/nativefx)")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--result")
    a = ap.parse_args()
    if a.result:
        return check_result(a.result)
    if not a.deps:
        ap.error("--deps or --result is required")
    deps = Path(a.deps)
    compiler, nativefx = deps / "vkd3d/vkd3d-compiler", deps / "tool/nativefx"
    results, failed, uninit = [], 0, 0
    with tempfile.TemporaryDirectory() as tmp:
        for name, profile, entry, src in cases():
            hlsl, binary = Path(tmp) / f"{name}.hlsl", Path(tmp) / f"{name}.bin"
            hlsl.write_text(src)
            r = subprocess.run([str(compiler), "-x", "hlsl", "-b", "d3dbc", "-p", profile, "-e", entry, str(hlsl),
                                "-o", str(binary)], capture_output=True, text=True)
            if r.returncode != 0:
                failed += 1
                print(f"FAIL compile {name} {profile}: {r.stderr.strip()}")
                continue
            t = subprocess.run([str(nativefx), "temp-check", str(binary)], capture_output=True, text=True)
            report = t.stdout.splitlines()[0].split(": ", 1)[1] if t.stdout else t.stderr.strip()
            m = re.match(r"\d+ temp component reads, (\d+) uninitialized, (\d+) c# limit, (\d+) swizzle, "
                         r"(\d+) output write", report)
            slot = "OVER SLOT LIMIT" in report
            print(f"{name} {profile}: {report}" + (" [known slot limit, 17b]" if slot else ""))
            # [TEMP] Over the slot limit is allowed until mul() emits dp4/dp3 (piece 17b); every other
            # finding fails.
            if not m or any(int(x) for x in m.groups()) or "LIMIT" in report.replace("OVER SLOT LIMIT", ""):
                uninit += 1
            results.append((name, profile, entry, src, binary.read_bytes(), slot))
    text = header(results)
    out = HERE / "sm1_jump_lowering_inputs.h"
    stale = 0
    if a.check:
        stale = int(not out.exists() or out.read_text() != text)
        if stale:
            print("FAIL: sm1_jump_lowering_inputs.h does not match this compiler's output (rerun without --check)")
    elif not failed:
        out.write_text(text)
    print(f"sm1 jump lowering: {len(results)} compiled, {failed} failed to compile, {uninit} break a validator rule "
          f"other than the slot limit, {sum(r[5] for r in results)} over the slot limit (known, 17b), header {'stale' if stale else 'current' if a.check else 'written'}")
    return 1 if failed or uninit or stale else 0


if __name__ == "__main__":
    sys.exit(main())
