#!/usr/bin/env python3
"""[CHOSEN, not recovered] Developer check, not used by the client.

Compares the requests a client run actually formed (the `requests/*.request` snapshots of a
fresh native cache, BF2_FX_NATIVE_CACHE=<empty dir>) with a reference set, by the
toolchain-independent refusal key (bf2fx::native::refusalKey, via `nativefx refusal-keys`):

  --enumerated DIR   request snapshots of enumerate_requests.py's set (build-cache.py
                     --capture-only), to prove the enumerator forms the client's requests;
  --table FILE       data/d3dx-refusals.txt, to prove the client's requests hit the table.

Prints the coverage and, for every client request not covered, the first line of its root
(the effect it belongs to), grouped. Exit status 1 when anything is uncovered, unless
--allow lists an accepted reason pattern (for example the .mfx metadata reflection compiles,
which the table does not record by design)."""
import argparse, collections, re, subprocess, sys, tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument("--client", type=Path, action="append", required=True, help="client cache directory (repeatable)")
ap.add_argument("--enumerated", type=Path, action="append", default=[], help="captured enumerated cache (repeatable)")
ap.add_argument("--table", type=Path, help="refusal table")
ap.add_argument("--tool", type=Path, default=REPO / "out/build/nativefx/tool/nativefx")
ap.add_argument("--allow", action="append", default=[], help="regex over an uncovered request's label")
a = ap.parse_args()
if not a.enumerated and not a.table:
    sys.exit("give --enumerated and/or --table")


def keys(paths):
    with tempfile.NamedTemporaryFile("w", dir=REPO / "out", delete=False, suffix=".txt") as f:
        f.write("\n".join(str(p.resolve()) for p in paths) + "\n")
        listing = Path(f.name)
    out = subprocess.run([str(a.tool), "refusal-keys", str(listing)], capture_output=True, text=True, check=True).stdout
    listing.unlink()
    return {line.split()[0]: line.split()[1][:16] for line in out.splitlines()}


def label(path):
    b = path.read_bytes()
    m = re.search(rb"// AutoGenerated shader file ([^\r\n]+)", b)
    if m:
        return "ra_generated " + re.sub(rb"(rashader[a-z0-9]*?)(has|use|nothing|pointlight).*", rb"\1", m.group(1)).decode("cp1252")
    if b"There were no techniques" in b or b"metadata" in b[:4096]:
        return "metadata"
    m = re.search(rb"(shaders/[A-Za-z0-9_]+\.(?:fx|mfx|dfx))", b)
    return "root " + (m.group(1).decode() if m else "?")


client = [p for d in a.client for p in sorted((d / "requests").glob("*.request"))]
ck = keys(client)
reference = set()
if a.enumerated:
    reference |= set(keys([p for d in a.enumerated for p in sorted((d / "requests").glob("*.request"))]).values())
if a.table:
    reference |= {l.split()[0] for l in a.table.read_text().splitlines() if l.strip() and not l.startswith("#")}
missing = collections.Counter()
for p in client:
    k = ck.get(p.stem) or ck.get(p.name)
    if k is None:
        k = next((v for kk, v in ck.items() if kk.endswith(p.stem)), None)
    if k not in reference:
        missing[label(p)] += 1
covered = len(client) - sum(missing.values())
print(f"client requests {len(client)}, covered {covered}, uncovered {sum(missing.values())}")
bad = 0
for lab, n in missing.most_common():
    ok = any(re.search(x, lab) for x in a.allow)
    print(f"  {n:6d} {'(allowed) ' if ok else ''}{lab}")
    bad += 0 if ok else n
sys.exit(1 if bad else 0)
