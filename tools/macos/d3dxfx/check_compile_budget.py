#!/usr/bin/env python3
"""[CHOSEN, not recovered] Developer check, not used by the client.

Compiles request snapshots (a client cache's requests/*.request, or an enumerated capture)
with the native compiler (`nativefx native-compile`) and fails when any one exceeds the time
budget or is refused while the D3DX table accepts it (`known 0` = Accepted). Used for the xpack
night shaders (RaShaderSTM shadow permutations), which stalled the level load when vkd3d's SM1/2
loop unrolling ran to its 1024-iteration limit. --test-accept sets the effect layer's test hook
(BF2_FX_TEST_HIGHER_VERTEX_PROFILE) so requests not yet in the table take the internal vs_3_0
path as accepted requests do."""
import argparse, os, re, subprocess, sys, time
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument("requests", type=Path, nargs="+", help="request snapshot files or directories")
ap.add_argument("--tool", type=Path, default=REPO / "out/build/nativefx/tool/nativefx")
ap.add_argument("--budget", type=float, default=5.0, help="seconds per request")
ap.add_argument("--match", default="", help="regex over the snapshot's generated-shader name")
ap.add_argument("--test-accept", action="store_true")
a = ap.parse_args()
files = []
for p in a.requests:
    files += sorted(p.glob("*.request")) if p.is_dir() else [p]
env = dict(os.environ)
if a.test_accept:
    env["BF2_FX_TEST_HIGHER_VERTEX_PROFILE"] = "1"
bad = checked = 0
for f in files:
    b = f.read_bytes()
    m = re.search(rb"// AutoGenerated shader file ([^\r\n]+)", b)
    name = m.group(1).decode("cp1252") if m else f.name
    if a.match and not re.search(a.match, name):
        continue
    t0 = time.monotonic()
    try:
        out = subprocess.run([str(a.tool), "native-compile", str(f)], capture_output=True, text=True,
                             env=env, timeout=a.budget * 4).stdout
    except subprocess.TimeoutExpired:
        out = "TIMEOUT"
    dt = time.monotonic() - t0
    checked += 1
    refused = out.startswith("kind 1") or out == "TIMEOUT"
    accepted = " known 0 " in out or a.test_accept
    if dt > a.budget or (refused and accepted):
        bad += 1
        print(f"FAIL {dt:6.2f}s {name}: {out.splitlines()[0] if out else '?'} {out.splitlines()[1][:160] if len(out.splitlines()) > 1 else ''}")
print(f"checked {checked}, failed {bad} (budget {a.budget}s)")
sys.exit(1 if bad else 0)
