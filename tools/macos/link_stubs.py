#!/usr/bin/env python3
# [TEMP] [CHOSEN, not recovered] link_stubs.py OUT.cpp OBJ... - test-only link stubs.
#
# Lets a unit check link one real engine TU without the rest of the engine: every dice:: symbol the
# objects reference but none of them defines becomes a definition in OUT.cpp. Functions abort with
# their demangled name (a check that reaches one is wrong and says where); vtables, typeinfo and other
# data become zero-filled blocks, which is safe because the checks never use an object whose
# constructor would store such a vtable. Symbol names are matched exactly through asm labels.
# Used by bf2_camera_shake_check (CMakeLists.txt). Mach-O x86_64/arm64 (nm names carry the leading _).
import subprocess
import sys


def nm(args, objects):
    out = subprocess.run(['nm'] + args + objects, capture_output=True, text=True, check=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if parts and not line.endswith(':'):
            names.add(parts[-1])
    return names


def main():
    out_path, objects = sys.argv[1], sys.argv[2:]
    undefined = nm(['-u'], objects)
    defined = nm(['-gU'], objects) | nm(['-U'], objects)
    wanted = sorted(s for s in undefined - defined if s.startswith('__Z') and '4dice' in s)
    demangled = subprocess.run(['c++filt'], input='\n'.join(wanted),
                               capture_output=True, text=True, check=True).stdout.splitlines()
    lines = [
        '// Generated by tools/macos/link_stubs.py for a unit check. Do not edit.',
        '#include <cstdio>',
        '#include <cstdlib>',
        'namespace {',
        '[[noreturn]] void reached(const char* name)',
        '{',
        '    std::fprintf(stderr, "[TEMP] link stub reached: %s\\n", name);',
        '    std::fflush(stderr);',
        '    std::abort();',
        '}',
        '} // namespace',
    ]
    for index, (symbol, name) in enumerate(zip(wanted, demangled)):
        is_data = symbol[1:].startswith(('_ZTV', '_ZTI', '_ZTS', '_ZGV')) or '(' not in name
        quoted = name.replace('\\', '\\\\').replace('"', '\\"')
        if is_data:
            lines.append('extern "C" { alignas(16) char stub_data_%d[512] __asm__("%s") = {}; }  // %s'
                         % (index, symbol, name))
        else:
            lines.append('extern "C" void stub_fn_%d() __asm__("%s");' % (index, symbol))
            lines.append('extern "C" void stub_fn_%d() { reached("%s"); }' % (index, quoted))
    with open(out_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('link_stubs: %d stubs for %d objects' % (len(wanted), len(objects)))


if __name__ == '__main__':
    main()
