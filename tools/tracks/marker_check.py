#!/usr/bin/env python3
"""Check [FRONTIER] markers against the function bodies they describe.

    python3 tools/tracks/marker_check.py [PATH ...] [--tsv OUT] [--fail-on-stale]

PATH: repo-relative directories or files (default: the rend track's paths). Every .cpp/.h/.inl/.mm
under them is parsed with the source parser of tools/ai-reconstruct/build_ledger.py (comments and
strings blanked, brace-aware). Python 3 standard library only.

A *stop* is an executable call that ends the run at an unwritten body:
  - std::abort() / abort();
  - a call to an identifier containing "frontier" (renddx9abi::frontier, bf2metal::frontier,
    bf2fx::frontier, RD9_FRONTIER, RD9_FRONTIER_AT, ...) other than the report-and-continue
    helpers listed below;
  - a call to a function-like macro whose #define (in the scanned files or Code/RendDX9Abi) expands
    to a stop, or to a noreturn/frontier-named helper whose own body stops (to a fixed point);
  - an invocation of such a macro at namespace scope (a macro that defines a whole stop body);
  - a thin forwarder (at most two statements, no nested block) whose callee is any of the above,
    including a function generated by a namespace-scope stop macro (to a fixed point).
Propagation through a forwarder is qualified, never by bare name: a qualified call matches stopping
functions whose namespace/class path ends with the call's path; an unqualified call inside a class
member matches the same class (then its bases, parsed from the source) and only then a free function
of an enclosing namespace of the caller (or a function generated in the same file by a stop macro).
When the callee cannot be tied to a stopping definition the call does not propagate (a missed stop
is preferred over an invented one). Direct stops (abort, frontier names, stop macros) match by name.
Calls made only when a constant switch is set (eccoreSeam's kECCoreSeamStops) are still counted:
the scan does not evaluate conditions, so read the listed body before acting on it.

Report-and-continue helpers (AGENTS.md seam exceptions) are counted as `seam`, not as stops:
identifiers containing "Seam" or "seam".

Each finding is one row:
  stale    a definition whose attached comment (the block directly above it, its declarator and
           opening line) carries [FRONTIER], but whose body contains no stop and no [FRONTIER] text.
           Three causes, so review every row: the tag is stale (remove it); it describes a gap in
           another function (a cross-reference, keep it accurate); or the body is a silent partial
           (it returns without the retail behaviour; recover it or put a stop at the gap).
  decl     a declaration whose attached comment carries [FRONTIER] while a definition with the same
           qualified name and parameter count exists in the scanned files and does not stop.
  partial  a definition without a stop whose body contains a [FRONTIER] comment: the body continues
           past a documented gap. Allowed only for the AGENTS.md exceptions; otherwise a stop
           belongs at the gap.
  abort    a definition (or a namespace-scope macro invocation) that stops: a live frontier body.
  seam     a definition that calls a report-and-continue seam helper.
  free     a [FRONTIER] comment attached to no function (fields, file headers, block remarks).

Exit status: 0, or 1 with --fail-on-stale when any stale/decl row exists.
"""

import argparse
import collections
import csv
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(REPO, "tools", "ai-reconstruct"))
import build_ledger as bl  # noqa: E402

REND_PATHS = ["Code/BF2/RendDX9", "Code/BF2/RendMisc", "Code/BF2/Geom", "Code/BF2/Scene",
              "Code/BF2/Platform/Gfx"]
MACRO_DIRS = ["Code/RendDX9Abi"]
EXTS = (".cpp", ".h", ".inl", ".mm", ".hpp")
TAG = "[FRONTIER]"

CALL_RE = re.compile(r"(?<![\w.>])((?:[A-Za-z_]\w*::)*[A-Za-z_]\w*)\s*\(")
DEFINE_RE = re.compile(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)\(([^)]*)\)((?:.*\\\n)*.*)$", re.M)
BASE_STOPS = {"abort", "std::abort"}


def files_under(paths):
    out = []
    for p in paths:
        full = os.path.join(REPO, p)
        if os.path.isfile(full):
            out.append(p)
            continue
        for root, _, names in os.walk(full):
            for n in sorted(names):
                if n.endswith(EXTS):
                    out.append(os.path.relpath(os.path.join(root, n), REPO))
    return sorted(set(out))


def calls(code):
    return [m.group(1) for m in CALL_RE.finditer(code)]


def last(name):
    return name.split("::")[-1]


def is_seam(name):
    return "seam" in last(name).lower()


def is_frontier_name(name):
    return "frontier" in last(name).lower() and not is_seam(name)


def read(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8", errors="replace") as f:
        return f.read()


def collect_macros(rels):
    """name -> (expansion code, file). Comments and strings in the expansion are blanked."""
    macros = {}
    for rel in rels:
        text = read(rel)
        for m in DEFINE_RE.finditer(text):
            body = m.group(3).replace("\\\n", "\n")
            code, _ = bl.blank_code(body)
            macros[m.group(1)] = (code, rel)
    return macros


def stop_names(macros, defs):
    """Identifiers whose call stops: base names, frontier-named helpers, stopping macros and
    helper definitions whose body stops (iterated to a fixed point, so macro -> helper chains
    resolve)."""
    stops = set(BASE_STOPS)
    changed = True
    while changed:
        changed = False
        for name, (code, _) in macros.items():
            if name in stops or is_seam(name):
                continue
            if any(c in stops or last(c) in stops or is_frontier_name(c) for c in calls(code)):
                stops.add(name)
                changed = True
        for d in defs:
            name = d["comps"][-1] if d["comps"] else ""
            if not name or name in stops or is_seam(name):
                continue
            if not re.search(r"noreturn|frontier", d["head"], re.I):
                continue
            if body_stops(d["code"], stops):
                stops.add(name)
                changed = True
    return stops


def forwarder(code):
    """A body of at most two statements: a thin adapter whose behaviour is its callee's."""
    inner = code.strip()[1:-1]
    return inner.count(";") <= 2 and "{" not in inner


class StopResolver:
    """Resolves a call inside a definition to the stopping thin forwarders it can name.

    `eligible` holds the definitions that stop (id) and are thin forwarders; `generated` the
    (file, name) pairs of functions generated by namespace-scope stop macros; `bases` maps a class
    name to its base-class names (see class_bases)."""

    def __init__(self, defs, generated, bases):
        self.by_name = collections.defaultdict(list)
        for d in defs:
            if d["comps"]:
                self.by_name[d["comps"][-1]].append(d)
        self.generated = set(generated)
        self.bases = bases or {}
        self.eligible = set()

    @staticmethod
    def _full(d):
        return list(d["namespaces"]) + list(d["comps"])

    @staticmethod
    def _compatible(a, b):
        k = min(len(a), len(b))
        return k > 0 and a[-k:] == b[-k:]

    def _any(self, defs):
        return any(id(d) in self.eligible for d in defs)

    def stops(self, call, caller):
        """True when `call`, made inside definition `caller`, resolves to an eligible stopper."""
        parts = call.split("::")
        name = parts[-1]
        cands = self.by_name.get(name, [])
        if len(parts) > 1:
            return any(id(d) in self.eligible and self._full(d)[-len(parts):] == parts for d in cands)
        scope = list(caller["namespaces"]) + list(caller["comps"][:-1])
        if len(caller["comps"]) > 1:
            own = [d for d in cands if len(d["comps"]) > 1
                   and self._compatible(self._full(d)[:-1], scope)
                   and d["comps"][-2] == caller["comps"][-2]]
            if own:
                return self._any(own)
            seen, frontier = {caller["comps"][-2]}, [caller["comps"][-2]]
            while frontier:
                level = []
                for cls in frontier:
                    for base in self.bases.get(cls, ()):
                        if base not in seen:
                            seen.add(base)
                            level.append(base)
                found = [d for d in cands if len(d["comps"]) > 1 and d["comps"][-2] in level]
                if found:
                    return self._any(found)
                frontier = level
        if (caller["file"], name) in self.generated:
            return True
        ns = tuple(caller["namespaces"])
        for d in cands:
            if len(d["comps"]) != 1 or id(d) not in self.eligible:
                continue
            dns = tuple(d["namespaces"])
            if ns[:len(dns)] != dns:
                continue
            if "{anon}" in dns and d["file"] != caller["file"]:
                continue
            return True
        return False


BASE_RE = re.compile(r"\b(?:class|struct)\s+(\w+)\s*(?:final\s*)?:\s*([^{;]+)\{")


def class_bases(rels):
    """{class name: [base class names]} from `class X : public Y, Z {` heads (template arguments
    and namespace qualifiers dropped)."""
    out = collections.defaultdict(list)
    for rel in rels:
        code, _ = bl.blank_code(read(rel))
        for m in BASE_RE.finditer(code):
            for part in bl.split_top(m.group(2), ","):
                part = re.sub(r"\b(public|protected|private|virtual)\b", " ", bl.strip_templates(part))
                ident = part.strip().split("::")[-1].strip()
                if re.fullmatch(r"\w+", ident) and ident not in out[m.group(1)]:
                    out[m.group(1)].append(ident)
    return dict(out)


def propagate(defs, stops, generated, bases=None):
    """Ids of the definitions that stop: directly (body_stops), or (to a fixed point) as a thin
    forwarder whose callee resolves, qualified, to a stopping thin forwarder or to a function
    generated by a namespace-scope stop macro. `generated` is [(file, name)]."""
    resolver = StopResolver(defs, generated, bases)
    direct = {id(d) for d in defs if body_stops(d["code"], stops)}
    resolver.eligible = {id(d) for d in defs if id(d) in direct and d["comps"] and forwarder(d["code"])}
    changed = True
    while changed:
        changed = False
        for d in defs:
            if id(d) in direct or not d["comps"] or not forwarder(d["code"]):
                continue
            if any(resolver.stops(c, d) for c in calls(d["code"])):
                direct.add(id(d))
                resolver.eligible.add(id(d))
                changed = True
    return direct


def body_stops(code, stops):
    for c in calls(code):
        if c in stops or last(c) in stops or is_frontier_name(c):
            return True
    return False


def body_seams(code):
    return any(is_seam(c) for c in calls(code))


def after_macro_invocations(code, start, end):
    """Position of the declarator in code[start:end] (comments blanked): `start`, or the first
    non-blank character after the last line-start function-like macro invocation (upper-case name)
    whose closing parenthesis ends its line. Such an invocation is a complete namespace-scope
    statement, never part of the following declarator."""
    pos = start
    stop = end if end >= 0 else len(code)
    for m in MACRO_CALL_RE.finditer(code, start, stop):
        if m.start(1) < pos:
            continue
        close = bl.find_matching(code, m.end() - 1, "(", ")")
        if close < 0 or close >= stop:
            continue
        eol = code.find("\n", close)
        eol = len(code) if eol < 0 else eol
        if code[close + 1:eol].strip(" \t\r;"):
            continue
        nxt = close + 1
        while nxt < stop and code[nxt] in " \t\r\n;":
            nxt += 1
        if nxt >= stop:
            continue
        pos = nxt
    return pos


def scan(rels):
    defs, decls, frees = [], [], []
    for rel in rels:
        text = read(rel)
        fdefs, fdecls, _ = bl.parse_file(rel)
        line_starts = [0] + [i + 1 for i, c in enumerate(text) if c == "\n"]
        code_text, comment_spans = bl.blank_code(text)
        for d in fdefs:
            d["code"], _ = bl.blank_code(d["body"])
            start = line_starts[d["line"] - 1]
            brace = text.find("{", start)
            hs = after_macro_invocations(code_text, start, brace)
            if hs != start:
                # namespace-scope macro invocations without a trailing ';' (console bindings) sat
                # between the previous statement and this declarator: the parser took them as the
                # head, so the comment block spanned every citation above them. Restart the head
                # and the attached comment after the last such invocation.
                d["line"] = bl.line_of(line_starts, hs)
                start = line_starts[d["line"] - 1]
                cstart = min(bl.attached_comment_start(text, line_starts, d["line"]), hs)
                eol = text.find("\n", brace)
                eol = len(text) if eol < 0 else eol
                d["comment"] = bl.comment_text(text, comment_spans, cstart, eol + 1)
            # the declarator plus the lines right above it, but never the previous definition's tail
            before = text[max(0, start - 200):start]
            before = before[max(before.rfind("}"), before.rfind(";")) + 1:]
            d["head"] = before + text[start:brace if brace >= 0 else start]
            body_start = brace if brace >= 0 else start
            d["span"] = (body_start, body_start + len(d["body"]))
            defs.append(d)
        decls.extend(fdecls)
        # every [FRONTIER] comment line, for the free/attached accounting
        _, comments = bl.blank_code(text)
        for s, e in comments:
            if TAG in text[s:e]:
                frees.append((rel, bl.line_of(line_starts, s), text[s:e].strip(), s))
    return defs, decls, frees


def analyse(rels):
    """Parse `rels` and classify stops. Returns (defs, decls, tags, stopping, invocations, stops):
    `stopping` is the set of id(def) whose body stops (directly or as a thin forwarder),
    `invocations` the namespace-scope stop-macro bodies, `stops` the stopping identifiers."""
    r = analyse_ex(rels)
    return r["defs"], r["decls"], r["tags"], r["stopping"], r["invocations"], r["stops"]


def analyse_ex(rels):
    """analyse() as a dict, plus `citations`: the namespace-scope invocations of non-stop macros
    (see macro_citations) and `macros`."""
    macros = collect_macros(rels + files_under(MACRO_DIRS))
    defs, decls, tags = scan(rels)
    stops = stop_names(macros, defs)
    invocations = macro_invocations(rels, defs, macros, stops)
    stopping = propagate(defs, stops, [(inv[0], inv[3]) for inv in invocations], class_bases(rels))
    citations = macro_citations(rels, defs, macros, stops, invocations)
    return {"defs": defs, "decls": decls, "tags": tags, "stopping": stopping,
            "invocations": invocations, "stops": stops, "macros": macros, "citations": citations}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("paths", nargs="*", default=REND_PATHS)
    ap.add_argument("--tsv", help="write all rows to this TSV")
    ap.add_argument("--fail-on-stale", action="store_true")
    ap.add_argument("--quiet", action="store_true", help="print only the summary")
    a = ap.parse_args()

    rels = files_under(a.paths)
    defs, decls, tags, stopping, invocations, stops = analyse(rels)

    rows = []
    def_index = collections.defaultdict(list)
    for d in defs:
        key = tuple(c for c in d["comps"])
        def_index[(key[-2:] if len(key) > 1 else key, d["nparams"])].append(d)

    for d in defs:
        name = "::".join(d["comps"])
        stops_here = id(d) in stopping
        seam_here = body_seams(d["code"])
        tag_comment = TAG in d["comment"]
        tag_body = TAG in d["body"]
        if stops_here:
            kind = "abort"
        elif tag_comment and not tag_body:
            kind = "stale"
        elif tag_body:
            kind = "partial"
        elif seam_here:
            kind = "seam"
        else:
            kind = None
        if kind:
            rows.append((kind, d["file"], d["line"], name, first_tag_line(d)))

    for decl in decls:
        if TAG not in decl["comment"]:
            continue
        key = tuple(decl["comps"])
        cands = def_index.get((key[-2:] if len(key) > 1 else key, decl["nparams"]), [])
        if cands and all(id(c) not in stopping and TAG not in c["body"] for c in cands):
            where = ", ".join("%s:%d" % (c["file"], c["line"]) for c in cands)
            rows.append(("decl", decl["file"], decl["line"], "::".join(decl["comps"]),
                         "defined at " + where))

    for rel, line, text_, fn in invocations:
        rows.append(("abort", rel, line, text_, "macro body"))

    # free tags: comments carrying [FRONTIER] that no def/decl comment or body contains
    attached = collections.defaultdict(list)
    for d in defs:
        attached[d["file"]].append(d["comment"] + "\n" + d["body"])
    for decl in decls:
        attached[decl["file"]].append(decl["comment"])
    for rel, line, ctext, _ in tags:
        if not any(ctext in blob for blob in attached[rel]):
            rows.append(("free", rel, line, "", ctext[:160]))

    rows.sort(key=lambda r: (r[0], r[1], r[2]))
    counts = collections.Counter(r[0] for r in rows)
    if a.tsv:
        with open(a.tsv, "w", newline="") as f:
            w = csv.writer(f, delimiter="\t", lineterminator="\n")
            w.writerow(["kind", "file", "line", "function", "note"])
            w.writerows(rows)
    if not a.quiet:
        for r in rows:
            if r[0] in ("stale", "decl", "partial"):
                print("%-7s %s:%d  %s  | %s" % (r[0], r[1], r[2], r[3], r[4][:140]))
    print("marker_check: %d files; " % len(rels)
          + ", ".join("%s %d" % (k, counts.get(k, 0))
                      for k in ("stale", "decl", "partial", "abort", "seam", "free")))
    if a.fail_on_stale and (counts.get("stale") or counts.get("decl")):
        return 1
    return 0


def macro_invocations(rels, defs, macros, stops):
    """Namespace-scope invocations of macros that expand to a whole stopping body:
    [(file, line, invocation text, generated function name)]."""
    out = []
    for rel in rels:
        text = read(rel)
        code, _ = bl.blank_code(text)
        line_starts = [0] + [i + 1 for i, c in enumerate(text) if c == "\n"]
        spans = [d["span"] for d in defs if d["file"] == rel]
        for m in re.finditer(r"(?m)^[ \t]*([A-Z][A-Z0-9_]*)\s*\(", code):
            name = m.group(1)
            if name not in stops or name not in macros or "{" not in macros[name][0]:
                continue
            pos = m.start(1)
            if any(s <= pos < e for s, e in spans):
                continue
            arg_end = bl.find_matching(code, m.end() - 1, "(", ")")
            args = re.sub(r"\s+", " ", text[m.end():arg_end]).strip()
            first = args.split(",")[0].strip()
            out.append((rel, bl.line_of(line_starts, pos), "%s(%s)" % (name, args), first))
    return out


MACRO_CALL_RE = re.compile(r"(?m)^[ \t]*([A-Z][A-Z0-9_]*)\s*\(")


def macro_citations(rels, defs, macros, stops, invocations):
    """Namespace-scope invocations of function-like macros that are not whole stop bodies (those
    are `invocations`), such as the console-binding BF2_CONSOLE_* macros:
    [{file, line, name, label, comment, text, stops}]. `comment` is the comment block directly
    above the invocation plus any comment on its first line; `label` the first macro argument
    (quotes dropped); `stops` is True when the macro expands to a stop or the invocation text
    carries [FRONTIER] or a stopping call in its arguments."""
    skip = {(i[0], i[1]) for i in invocations}
    out = []
    for rel in rels:
        text = read(rel)
        code, comments = bl.blank_code(text)
        line_starts = [0] + [i + 1 for i, c in enumerate(text) if c == "\n"]
        spans = [d["span"] for d in defs if d["file"] == rel]
        for m in MACRO_CALL_RE.finditer(code):
            name = m.group(1)
            pos = m.start(1)
            line = bl.line_of(line_starts, pos)
            if (rel, line) in skip or any(s <= pos < e for s, e in spans):
                continue
            if name not in macros and not name.startswith(("BF2_", "RD9_")):
                continue
            arg_end = bl.find_matching(code, m.end() - 1, "(", ")")
            if arg_end < 0:
                continue
            args = re.sub(r"\s+", " ", text[m.end():arg_end]).strip()
            label = args.split(",")[0].strip().strip('"')
            cstart = min(bl.attached_comment_start(text, line_starts, line), pos)
            eol = text.find("\n", pos)
            eol = len(text) if eol < 0 else eol
            ctext = bl.comment_text(text, comments, cstart, eol + 1)
            macro_stops = (name in stops or is_frontier_name(name) or TAG in text[pos:arg_end + 1]
                           or body_stops(code[m.end():arg_end], stops))
            out.append({"file": rel, "line": line, "name": name, "label": label,
                        "comment": ctext, "text": "%s(%s)" % (name, args), "stops": macro_stops})
    return out


def first_tag_line(d):
    for blob in (d["comment"], d["body"]):
        for ln in blob.split("\n"):
            if TAG in ln:
                return re.sub(r"\s+", " ", ln.strip())
    return ""


if __name__ == "__main__":
    sys.exit(main())
